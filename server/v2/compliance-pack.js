function testPlan(f, products) {
  const want = (p) => !products || products[p.toLowerCase()] !== false;
  const catalog = Object.fromEntries((f.controls || []).map(c => [c.id, c.name]));
  const byControl = new Map();
  const add = (ctrl, row) => { if (!byControl.has(ctrl)) byControl.set(ctrl, []); byControl.get(ctrl).push(row); };
  for (const t of T.TESTS) {
    if (!want(t.product)) continue;
    const objs = TEST_OBJECTIVES[t.id] || [];
    const pv = T.PROVE[t.id] || null;
    const row = { test: t.id, title: t.title, product: t.product, steps: t.steps.join(' '), expect: t.expect, prove: pv ? `${pv.type}: ${pv.target}` : '' };
    const ctrls = [...new Set(objs.flatMap(o => (f.objectives || {})[o] || []))];
    if (!ctrls.length) add('—', { ...row, why: 'Not mapped to this profile (shown as a differentiating or operational test).' });
    for (const c of ctrls) add(c, row);
  }
  for (const br of (f.dlp && f.dlp.blockRules) || []) for (const c of br.controls || []) add(c, { test: `dlp-${br.key}`, title: `DLP: ${br.label}`, product: 'ZIA',
    steps: `Download the ${br.label} test file from the test kit and upload it to https://dlptest.com/http-post/ through ZIA.`, expect: 'Block mode: blocked, incident names the rule. Monitor mode: allowed and logged.', prove: '' });
  const order = (f.controls || []).map(c => c.id);
  return [...byControl.entries()].sort((a, b) => (order.indexOf(a[0]) + 1 || 999) - (order.indexOf(b[0]) + 1 || 999))
    .map(([control, tests]) => ({ control, name: catalog[control] || (control === '—' ? 'Not mapped' : control), tests }));
}

