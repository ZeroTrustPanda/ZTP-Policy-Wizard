const NOTE = { 'Self-Harm': 'Use the sample text in Zscaler\'s cyberbullying engine documentation; the wizard does not generate this content.' };

function frameworkOf(baselineId) { return fw.getBaseline(baselineId); }

/** Test files for the profile's DLP rules (block and monitor mode use the same data). */
function profileFiles(f) {
  const rules = (f.dlp && f.dlp.blockRules) || [];
  return rules.map(br => ({ id: `cp-${f.id}-${br.key}`, rule: br.key, label: `${br.label}`, controls: br.controls || [],
    name: `zscaler-pov-${f.id.toLowerCase()}-${br.key.toLowerCase()}-test.csv`, available: !!SAMPLE[br.key], note: NOTE[br.key] || null }));
}
function profileFile(id) {
  const m = /^cp-([A-Z0-9_]+)-(.+)$/.exec(String(id || ''));
  if (!m) throw Object.assign(new Error('Unknown compliance test file.'), { status: 404 });
  const f = frameworkOf(m[1]);
  const br = ((f.dlp && f.dlp.blockRules) || []).find(b => b.key === m[2]);
  if (!br || !SAMPLE[br.key]) throw Object.assign(new Error('No generated test file for this rule.'), { status: 404 });
  const [head, ...rows] = SAMPLE[br.key]();
  return { name: `zscaler-pov-${f.id.toLowerCase()}-${br.key.toLowerCase()}-test.csv`, type: 'text/csv', content: csv(head, rows) };
}

